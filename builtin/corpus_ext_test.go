package builtin

// Real-image tests for the ext family, against e2fsprogs.
//
// WHY e2fsprogs. Every ext_* builtin reaches the volume through
// github.com/aoiflux/libext, and the fake backend in the unit tests answers
// whatever its fixture was told to answer. A fixture is built from the same
// reading of the format as the parser, so neither can catch a misreading of
// the format. e2fsprogs shares no code and no reasoning with libext, so where
// the two agree about a field the agreement means something.
//
// WHY debugfs AND NOT A MOUNT. A loop mount needs root and the machine that
// produced these numbers had none. debugfs reads the image file directly and
// answers every question a builtin publishes, which is what made an ext4
// content oracle reachable where exFAT's still is not: exfatprogs has no
// per-file content dump, so exFAT has geometry and counts but no digests.
//
// WHAT THIS FOUND. On img6_ext4.dd, nothing. Measured 2026-10-10 against
// e2fsprogs 1.47.0: all 1,827 directory entries agree with debugfs on path,
// inode, size and type; all 1,757 regular files hash byte-identical over
// 351,355,389 bytes; block_size and inodes_count match dumpe2fs; ext_verify's
// three checks agree with a clean `e2fsck -fn`; ext_deleted reports zero where
// `debugfs lsdel` reports zero; ext_journal's ten records are debugfs's seven
// descriptor blocks plus three revoke tables, over the same sequence range and
// ending at the same block; the absolute byte offset ext_slack reports for a
// file's tail is the block debugfs names plus the file's length; and the
// extended attributes match `ea_list` byte for byte, trailing NUL included.
//
// THREE THINGS THAT LOOKED LIKE DEFECTS AND WERE NOT. They are recorded
// because each one would have become a wrong ledger row:
//
//   - ext_journal reports ten records where `logdump -O -a` appears to name
//     fourteen sequence numbers. It does not: logdump prints both the on-disk
//     sequence and its own expected counter, under the same word, and the
//     on-disk set is 2..8 exactly as mutant reports.
//   - ext_report publishes size 4299210752 for inode 7 inside a 1 GiB image.
//     That is the real on-disk i_size of ext4's resize inode and debugfs
//     prints the same number.
//   - ext_report counts three entries no path reaches. They are inodes 7, 8
//     and 12 -- resize, journal, orphan file -- which its own scope says it
//     includes, and it marks them with a synthetic path that the readers
//     refuse. TestExtReportMarksTheInodesNoPathReaches pins that refusal.
//
// WHY NOTHING IS PINNED BY VALUE. The corpus images are regenerated and are
// not byte-reproducible, so no digest, count or offset is written into this
// file. Every comparison is either against an oracle regenerated beside the
// image, or between two builtins reading the same volume, or an invariant of
// the return contract. What each test does pin is that it reached something:
// every walk counts what it compared and fails at zero, so a wrong
// -corpus.dir cannot read as a green suite.
//
// THE ORACLE. img6_ext4.dd.ext4-oracle.tsv beside the image, as the FAT
// oracles sit beside theirs. Generated by ext4_oracle.py, which lives with the
// corpus rather than in this repository, as make_fat_oracle.py does in libfat.
// It drives debugfs and writes a header row then one row per entry. The tests
// that need it skip when it is absent, and say so.

import (
	"path/filepath"
	"sort"
	"strings"
	"testing"

	"mutant/object"
)

const (
	extCorpusImage  = "img6_ext4.dd"
	extCorpusOracle = extCorpusImage + ".ext4-oracle.tsv"
)

// extOracleEntry is one row of the e2fsprogs oracle.
type extOracleEntry struct {
	path      string
	inode     int64
	kind      string
	isDir     bool
	size      int64
	sha256    string
	blocks    int64
	firstByte int64
}

// extCorpusEntry is one entry as ext_list_files described it.
type extCorpusEntry struct {
	path  string
	name  string
	inode int64
	isDir bool
	size  int64
	del   bool
}

func openCorpusEXT(t *testing.T) (string, bool) {
	t.Helper()

	image, ok := corpusFile(t, extCorpusImage)
	if !ok {
		return "", false
	}

	payload, errObj := unwrapPair(t, ExtOpen(stringObj(image)))
	if errObj != nil {
		t.Fatalf("ext_open(%s): %s", image, errObj.Inspect())
	}
	openHash, okHash := payload.(*object.Hash)
	if !okHash {
		t.Fatalf("ext_open payload is not HASH. got=%T", payload)
	}

	handle := mustHashStringValue(t, openHash, "handle")
	t.Cleanup(func() { ExtClose(stringObj(handle)) })

	return handle, true
}

// extCorpusOracleRows reads the e2fsprogs oracle, or reports that it is absent.
//
// The column order is read from the header rather than assumed, so adding a
// column to the generator cannot silently shift every comparison by one.
func extCorpusOracleRows(t *testing.T) (map[string]extOracleEntry, bool) {
	t.Helper()

	path, ok := corpusFile(t, extCorpusOracle)
	if !ok {
		t.Logf("no %s in this copy of the corpus: the comparison against "+
			"e2fsprogs is skipped and only the cross-builtin checks run", extCorpusOracle)
		return nil, false
	}

	rows := corpusOracleLines(t, path)
	index := map[string]int{}
	for i, name := range rows[0].fields {
		index[strings.TrimSpace(name)] = i
	}
	for _, required := range []string{
		"path", "inode", "type", "isdir", "size", "sha256",
		"block_count", "first_byte_offset",
	} {
		if _, found := index[required]; !found {
			t.Fatalf("%s has no %q column; its header is %v",
				filepath.Base(path), required, rows[0].fields)
		}
	}

	out := map[string]extOracleEntry{}
	for _, row := range rows[1:] {
		field := func(name string) string {
			i := index[name]
			if i >= len(row.fields) {
				t.Fatalf("%s line %d has %d fields and %q is column %d",
					filepath.Base(path), row.line, len(row.fields), name, i+1)
			}
			return strings.TrimSpace(row.fields[i])
		}
		entry := extOracleEntry{
			path:   field("path"),
			inode:  oracleInt(t, path, row.line, field("inode")),
			kind:   field("type"),
			isDir:  field("isdir") == "True",
			size:   oracleInt(t, path, row.line, field("size")),
			sha256: field("sha256"),
		}
		// A directory leaves the placement columns empty, so they are read
		// only where the generator filled them.
		if text := field("block_count"); text != "" {
			entry.blocks = oracleInt(t, path, row.line, text)
		}
		if text := field("first_byte_offset"); text != "" {
			entry.firstByte = oracleInt(t, path, row.line, text)
		}
		if entry.path == "" {
			t.Fatalf("%s line %d names no path", filepath.Base(path), row.line)
		}
		out[entry.path] = entry
	}
	if len(out) == 0 {
		t.Fatalf("%s holds a header and no rows", filepath.Base(path))
	}
	return out, true
}

// extCorpusWalk descends the volume through ext_list_files, which is both how
// every file is found and one of the things being measured.
func extCorpusWalk(t *testing.T, handle, dir string, depth int, out *[]extCorpusEntry) {
	t.Helper()

	if depth > 64 {
		t.Fatalf("ext_list_files descended past 64 levels at %s, which a 1 GiB "+
			"volume has no reason to do", dir)
	}

	payload, errObj := unwrapPair(t, ExtListFiles(stringObj(handle), stringObj(dir)))
	if errObj != nil {
		t.Fatalf("ext_list_files(%s): %s", dir, errObj.Inspect())
	}
	rows, okArr := payload.(*object.Array)
	if !okArr {
		t.Fatalf("ext_list_files payload is not ARRAY. got=%T", payload)
	}

	for _, element := range rows.Elements {
		row, okRow := element.(*object.Hash)
		if !okRow {
			t.Fatalf("ext_list_files element is not HASH. got=%T", element)
		}
		entry := extCorpusEntry{
			name:  mustHashStringValue(t, row, "name"),
			path:  mustHashStringValue(t, row, "path"),
			inode: mustHashIntValue(t, row, "inode"),
			isDir: mustHashBoolValue(t, row, "is_dir"),
			size:  mustHashIntValue(t, row, "size"),
			del:   mustHashBoolValue(t, row, "deleted"),
		}
		if entry.name == "." || entry.name == ".." {
			continue
		}
		*out = append(*out, entry)
		if entry.isDir && !entry.del {
			extCorpusWalk(t, handle, entry.path, depth+1, out)
		}
	}
}

// extCorpusField reads one key of a result hash, for keys a test asks about
// rather than requires.
func extCorpusField(h *object.Hash, key string) (object.Object, bool) {
	pair, found := h.Pairs[(&object.String{Value: key}).HashKey()]
	if !found {
		return nil, false
	}
	return pair.Value, true
}

// extCorpusStrings reads an array-of-strings field as Go strings.
func extCorpusStrings(t *testing.T, h *object.Hash, key string) []string {
	t.Helper()

	value, found := extCorpusField(h, key)
	if !found {
		return nil
	}
	array, okArr := value.(*object.Array)
	if !okArr {
		t.Fatalf("%s is not an ARRAY. got=%T", key, value)
	}
	out := make([]string, 0, len(array.Elements))
	for _, element := range array.Elements {
		text, okStr := element.(*object.String)
		if !okStr {
			t.Fatalf("%s holds a %T rather than a STRING", key, element)
		}
		out = append(out, text.Value)
	}
	return out
}

// TestEveryExtFileReadsTheBytesE2fsprogsRead is the comparison the whole file
// exists for: the content, against a reader that shares no code with ours.
//
// It is not replaceable by the builtins agreeing with each other. On NTFS all
// five readers agreed about /$Secure and all five were wrong, because the
// attribute selection they shared was wrong underneath them (M26-FS1-022).
func TestEveryExtFileReadsTheBytesE2fsprogsRead(t *testing.T) {
	oracle, haveOracle := extCorpusOracleRows(t)
	if !haveOracle {
		t.Skip("no ext4 oracle beside the image")
	}
	handle, ok := openCorpusEXT(t)
	if !ok {
		return
	}

	var listed []extCorpusEntry
	extCorpusWalk(t, handle, "/", 0, &listed)

	reached := map[string]bool{}
	hashed, compared := 0, 0
	for _, entry := range listed {
		if entry.del {
			continue
		}
		reached[entry.path] = true

		want, found := oracle[entry.path]
		if !found {
			t.Errorf("ext_list_files reports %s and e2fsprogs did not: either the "+
				"oracle is stale against this image or the listing invented an entry",
				entry.path)
			continue
		}
		compared++
		if entry.isDir != want.isDir {
			t.Errorf("%s: ext_list_files says is_dir=%t, e2fsprogs says type %q",
				entry.path, entry.isDir, want.kind)
		}
		if entry.inode != want.inode {
			t.Errorf("%s: ext_list_files says inode %d, e2fsprogs says %d",
				entry.path, entry.inode, want.inode)
		}
		if !want.isDir && entry.size != want.size {
			t.Errorf("%s: ext_list_files says %d bytes, e2fsprogs says %d",
				entry.path, entry.size, want.size)
		}
		if want.kind != "regular" {
			continue
		}

		payload, errObj := unwrapPair(t, ExtHashFile(
			stringObj(handle), stringObj(entry.path), stringObj("sha256")))
		if errObj != nil {
			t.Errorf("ext_hash_file(%s) refused a file e2fsprogs read: %s",
				entry.path, errObj.Message)
			continue
		}
		result, okHash := payload.(*object.Hash)
		if !okHash {
			t.Fatalf("ext_hash_file payload is not HASH. got=%T", payload)
		}
		hashed++

		if got := mustHashStringValue(t, result, "digest"); got != want.sha256 {
			t.Errorf("%s: ext_hash_file digests %s, e2fsprogs digests %s "+
				"(mutant size %d, oracle size %d) -- the two readers disagree about "+
				"the bytes, which is the one disagreement this file cannot tolerate",
				entry.path, got, want.sha256,
				mustHashIntValue(t, result, "size"), want.size)
		}
		if truncated := mustHashBoolValue(t, result, "truncated"); truncated {
			t.Errorf("%s: ext_hash_file reports truncated on a file e2fsprogs read whole",
				entry.path)
		}
		if located := mustHashIntValue(t, result, "located_bytes"); located != want.size {
			t.Errorf("%s: ext_hash_file located %d bytes of the %d e2fsprogs read",
				entry.path, located, want.size)
		}
	}

	// The other direction: an entry the oracle holds and no walk reached is a
	// silent drop, which is the failure mode a count alone would hide.
	var dropped []string
	for path := range oracle {
		if !reached[path] {
			dropped = append(dropped, path)
		}
	}
	sort.Strings(dropped)
	if len(dropped) > 0 {
		shown := dropped
		if len(shown) > 12 {
			shown = shown[:12]
		}
		t.Errorf("e2fsprogs reaches %d entries ext_list_files never listed, beginning %v",
			len(dropped), shown)
	}

	if compared == 0 {
		t.Errorf("-corpus.dir is %q and not one ext entry was compared against "+
			"e2fsprogs: the suite would have reported this as a pass", *corpusDir)
	}
	if hashed == 0 {
		t.Errorf("-corpus.dir is %q and not one ext file was hashed", *corpusDir)
	}
	t.Logf("compared %d entries and %d file digests against e2fsprogs", compared, hashed)
}

// TestTheExtFamilyAgreesWithItselfAboutEveryLength needs no oracle, so it runs
// wherever the corpus does.
//
// Four builtins publish a length for the same file by three different routes:
// the directory listing, the inode read, and the streaming reader that
// ext_hash_file and ext_extract_file share. A disagreement between them is a
// defect whichever one is right, and this is the check that found both NTFS
// defects before any oracle existed for that volume.
func TestTheExtFamilyAgreesWithItselfAboutEveryLength(t *testing.T) {
	handle, ok := openCorpusEXT(t)
	if !ok {
		return
	}

	var listed []extCorpusEntry
	extCorpusWalk(t, handle, "/", 0, &listed)

	checked := 0
	for _, entry := range listed {
		if entry.del || entry.isDir {
			continue
		}

		payload, errObj := unwrapPair(t, ExtMetadata(stringObj(handle), stringObj(entry.path)))
		if errObj != nil {
			t.Errorf("ext_metadata(%s) refused a path ext_list_files had just listed: %s",
				entry.path, errObj.Message)
			continue
		}
		metadata, okHash := payload.(*object.Hash)
		if !okHash {
			t.Fatalf("ext_metadata payload is not HASH. got=%T", payload)
		}
		metaSize := mustHashIntValue(t, metadata, "size")
		if metaSize != entry.size {
			t.Errorf("%s: ext_list_files says %d bytes and ext_metadata says %d",
				entry.path, entry.size, metaSize)
		}
		if gotInode := mustHashIntValue(t, metadata, "inode"); gotInode != entry.inode {
			t.Errorf("%s: ext_list_files says inode %d and ext_metadata says %d",
				entry.path, entry.inode, gotInode)
		}

		payload, errObj = unwrapPair(t, ExtHashFile(
			stringObj(handle), stringObj(entry.path), stringObj("sha256")))
		if errObj != nil {
			t.Errorf("ext_hash_file(%s) refused a path ext_metadata described: %s",
				entry.path, errObj.Message)
			continue
		}
		digest, okHash := payload.(*object.Hash)
		if !okHash {
			t.Fatalf("ext_hash_file payload is not HASH. got=%T", payload)
		}
		hashSize := mustHashIntValue(t, digest, "size")
		located := mustHashIntValue(t, digest, "located_bytes")
		hashedBytes := mustHashIntValue(t, digest, "bytes_hashed")
		truncated := mustHashBoolValue(t, digest, "truncated")

		if hashSize != metaSize {
			t.Errorf("%s: ext_metadata says %d bytes and ext_hash_file says %d",
				entry.path, metaSize, hashSize)
		}
		if !truncated && hashedBytes != hashSize {
			t.Errorf("%s: ext_hash_file hashed %d of %d bytes and reports truncated "+
				"false, so a short read is being published as a whole-file digest",
				entry.path, hashedBytes, hashSize)
		}
		if located > hashSize {
			t.Errorf("%s: ext_hash_file located %d bytes of a %d byte file",
				entry.path, located, hashSize)
		}
		checked++
	}

	if checked == 0 {
		t.Errorf("-corpus.dir is %q and not one ext file was cross-checked", *corpusDir)
	}
	t.Logf("cross-checked %d files across the listing, the inode and the reader", checked)
}

// TestExtReportMarksTheInodesNoPathReaches pins behaviour that is right and
// could quietly stop being right.
//
// ext_report walks the inode table rather than the directory tree, which its
// own scope says, so it reports inodes nothing names -- the resize inode, the
// journal, the orphan file. It gives each one a synthetic path of the form
// "inode:N". The thing that must hold is that the synthetic path is never
// mistaken for a real one: a reader handed ext_report's rows must be refused
// when it asks for one, rather than answered about some other file.
func TestExtReportMarksTheInodesNoPathReaches(t *testing.T) {
	handle, ok := openCorpusEXT(t)
	if !ok {
		return
	}

	var listed []extCorpusEntry
	extCorpusWalk(t, handle, "/", 0, &listed)
	reachable := map[string]bool{"/": true}
	for _, entry := range listed {
		reachable[entry.path] = true
	}

	payload, errObj := unwrapPair(t, ExtReport(stringObj(handle)))
	if errObj != nil {
		t.Fatalf("ext_report: %s", errObj.Inspect())
	}
	report, okHash := payload.(*object.Hash)
	if !okHash {
		t.Fatalf("ext_report payload is not HASH. got=%T", payload)
	}

	filesObj, found := extCorpusField(report, "files")
	if !found {
		t.Fatalf("ext_report published no files array")
	}
	files, okArr := filesObj.(*object.Array)
	if !okArr {
		t.Fatalf("ext_report files is not an ARRAY. got=%T", filesObj)
	}
	if count := mustHashIntValue(t, report, "file_count"); count != int64(len(files.Elements)) {
		t.Errorf("ext_report says file_count %d and its files array holds %d",
			count, len(files.Elements))
	}

	unreachable := 0
	for _, element := range files.Elements {
		row, okRow := element.(*object.Hash)
		if !okRow {
			t.Fatalf("ext_report files element is not HASH. got=%T", element)
		}
		path := mustHashStringValue(t, row, "path")
		if path == "" {
			t.Errorf("ext_report row %s names no path at all, so nothing can be "+
				"asked about it and nothing says why",
				mustHashStringValue(t, row, "identity"))
			continue
		}
		if reachable[path] {
			continue
		}
		unreachable++

		// It must not resolve. An answer here would mean the synthetic name
		// collided with a real lookup.
		if _, err := unwrapPairNoFatal(ExtMetadata(stringObj(handle), stringObj(path))); err == nil {
			t.Errorf("ext_report gives %s a path no walk reaches, and "+
				"ext_metadata answers about it rather than refusing: a synthetic "+
				"name is resolving as a real one", path)
		}
		if _, err := unwrapPairNoFatal(ExtHashFile(
			stringObj(handle), stringObj(path), stringObj("sha256"))); err == nil {
			t.Errorf("ext_report gives %s a path no walk reaches, and "+
				"ext_hash_file digests it rather than refusing", path)
		}
	}

	if dirCount := mustHashIntValue(t, report, "directory_count"); dirCount <= 0 {
		t.Errorf("ext_report says directory_count %d on a volume with a root", dirCount)
	}
	t.Logf("ext_report holds %d rows, %d of them inodes no path reaches, and every "+
		"one of those is refused by the readers", len(files.Elements), unreachable)
}

// TestExtDeletedSaysWhichSourcesItCouldNotUse is the two-bit contract on the
// deleted scan: an empty answer has to be distinguishable from an unasked
// question.
//
// On a volume with nothing deleted the entry list is empty either way, so the
// only thing that separates "looked and found none" from "could not look" is
// whether the sources it could not consult are named.
func TestExtDeletedSaysWhichSourcesItCouldNotUse(t *testing.T) {
	handle, ok := openCorpusEXT(t)
	if !ok {
		return
	}

	payload, errObj := unwrapPair(t, ExtDeleted(stringObj(handle)))
	if errObj != nil {
		t.Fatalf("ext_deleted: %s", errObj.Inspect())
	}
	scan, okHash := payload.(*object.Hash)
	if !okHash {
		t.Fatalf("ext_deleted payload is not HASH. got=%T", payload)
	}

	entriesObj, found := extCorpusField(scan, "entries")
	if !found {
		t.Fatalf("ext_deleted published no entries array")
	}
	entries := entriesObj.(*object.Array)
	if count := mustHashIntValue(t, scan, "entry_count"); count != int64(len(entries.Elements)) {
		t.Errorf("ext_deleted says entry_count %d and its entries array holds %d",
			count, len(entries.Elements))
	}

	sources := extCorpusStrings(t, scan, "sources")
	unavailable := extCorpusStrings(t, scan, "sources_unavailable")
	if len(sources) == 0 && len(unavailable) == 0 {
		t.Errorf("ext_deleted names neither the sources it consulted nor the ones " +
			"it could not, so an empty result cannot be told from an unasked question")
	}
	for _, name := range unavailable {
		for _, consulted := range sources {
			if name == consulted {
				t.Errorf("ext_deleted names %q as both consulted and unavailable", name)
			}
		}
	}

	// examined counts what the scan looked at. A scan reporting no entries and
	// examining nothing has not established that there is nothing.
	if len(entries.Elements) == 0 {
		if examined := mustHashIntValue(t, scan, "examined"); examined <= 0 {
			t.Errorf("ext_deleted reports no deleted entries and examined %d slots, "+
				"which says nothing was looked at rather than that nothing was found",
				examined)
		}
	}
	t.Logf("ext_deleted: %d entries, sources %v, unavailable %v",
		len(entries.Elements), sources, unavailable)
}

// TestExtJournalRaisesTheRevokeRecordsItCannotParse pins the one warning this
// volume's journal must produce.
//
// libext identifies revoke records and does not parse them: they come back with
// no tags and a block count of zero. A revoke is precisely the statement that a
// journalled copy must not be replayed, so a journal holding them and not
// saying so would let ext_journal_block_copies offer copies that cannot be
// shown to be valid. The warning is the only thing standing between those two
// facts, and it is cheap to lose in a refactor.
func TestExtJournalRaisesTheRevokeRecordsItCannotParse(t *testing.T) {
	handle, ok := openCorpusEXT(t)
	if !ok {
		return
	}

	payload, errObj := unwrapPair(t, ExtJournal(stringObj(handle)))
	if errObj != nil {
		t.Fatalf("ext_journal: %s", errObj.Inspect())
	}
	scan, okHash := payload.(*object.Hash)
	if !okHash {
		t.Fatalf("ext_journal payload is not HASH. got=%T", payload)
	}

	if !mustHashBoolValue(t, scan, "present") {
		t.Skip("this volume carries no journal")
	}
	if !mustHashBoolValue(t, scan, "wrap_checked") {
		t.Errorf("ext_journal reports wrap_checked false, so `wrapped` says nothing " +
			"and `committed` on every entry is unusable")
	}

	entriesObj, found := extCorpusField(scan, "entries")
	if !found {
		t.Fatalf("ext_journal published no entries array")
	}
	entries := entriesObj.(*object.Array)
	if count := mustHashIntValue(t, scan, "entry_count"); count != int64(len(entries.Elements)) {
		t.Errorf("ext_journal says entry_count %d and its entries array holds %d",
			count, len(entries.Elements))
	}

	// A record with no tags is how a revoke reads here. Whenever one is
	// present, the warning naming them has to be present too.
	revokes := 0
	for _, element := range entries.Elements {
		row := element.(*object.Hash)
		if mustHashIntValue(t, row, "tag_count") == 0 {
			revokes++
		}
	}
	codes := extCorpusStrings(t, scan, "warning_codes")
	hasRevokeWarning := false
	for _, code := range codes {
		if code == "revoke_records_not_parsed" {
			hasRevokeWarning = true
		}
	}
	switch {
	case revokes > 0 && !hasRevokeWarning:
		t.Errorf("ext_journal reports %d records carrying no block tags, which is how "+
			"a revoke reads, and raises no revoke_records_not_parsed warning: the "+
			"blocks those records invalidate are unknown and nothing says so. "+
			"warning_codes was %v", revokes, codes)
	case revokes == 0 && hasRevokeWarning:
		t.Errorf("ext_journal raises revoke_records_not_parsed and reports no record " +
			"without tags")
	}
	t.Logf("ext_journal: %d records, %d of them revokes, warning_codes %v",
		len(entries.Elements), revokes, codes)
}

// TestExtSlackIsTheTailOfTheLastBlock checks the arithmetic, and against the
// oracle the physical placement too.
//
// The arithmetic needs no oracle: a file's slack is what its allocation holds
// past its length, so size plus the slack classes must come to the allocation.
// The placement does need one, and it is the stronger check: an absolute byte
// offset agreeing with the block e2fsprogs names means the extent map was read
// the same way by both readers, which is what the cross-builtin checks cannot
// establish on their own.
func TestExtSlackIsTheTailOfTheLastBlock(t *testing.T) {
	oracle, haveOracle := extCorpusOracleRows(t)
	handle, ok := openCorpusEXT(t)
	if !ok {
		return
	}

	var listed []extCorpusEntry
	extCorpusWalk(t, handle, "/", 0, &listed)

	checked, placed := 0, 0
	for _, entry := range listed {
		if entry.del || entry.isDir || entry.size == 0 {
			continue
		}

		payload, errObj := unwrapPairNoFatal(ExtSlack(stringObj(handle), stringObj(entry.path)))
		if errObj != nil {
			// A refusal is allowed and is not what this test is about; a wrong
			// number is.
			continue
		}
		slack, okHash := payload.(*object.Hash)
		if !okHash {
			t.Fatalf("ext_slack payload is not HASH. got=%T", payload)
		}

		size := mustHashIntValue(t, slack, "size")
		allocated := mustHashIntValue(t, slack, "allocated_bytes")
		fileSlack := mustHashIntValue(t, slack, "file_slack_bytes")
		unwritten := mustHashIntValue(t, slack, "unwritten_bytes")

		if size != entry.size {
			t.Errorf("%s: ext_list_files says %d bytes and ext_slack says %d",
				entry.path, entry.size, size)
		}
		if !mustHashBoolValue(t, slack, "file_slack_checked") {
			continue
		}
		if allocated > 0 && size+fileSlack+unwritten != allocated {
			t.Errorf("%s: ext_slack says size %d + file_slack %d + unwritten %d, "+
				"which is %d, and allocated_bytes %d: the tail does not account for "+
				"the allocation", entry.path, size, fileSlack, unwritten,
				size+fileSlack+unwritten, allocated)
		}
		if fileSlack < 0 || unwritten < 0 {
			t.Errorf("%s: ext_slack reports a negative length (file_slack %d, "+
				"unwritten %d)", entry.path, fileSlack, unwritten)
		}
		checked++

		// The placement. For a file held in one block, the tail begins at that
		// block plus the file's length, and e2fsprogs names the block. This is
		// an absolute offset into the image compared against an independent
		// reader's extent map, which no amount of internal agreement can
		// substitute for.
		if !haveOracle {
			continue
		}
		want, found := oracle[entry.path]
		if !found || want.blocks != 1 || want.firstByte == 0 || fileSlack == 0 {
			continue
		}
		rangesObj, haveRanges := extCorpusField(slack, "ranges")
		if !haveRanges {
			continue
		}
		ranges := rangesObj.(*object.Array)
		if len(ranges.Elements) == 0 {
			continue
		}
		first := ranges.Elements[0].(*object.Hash)
		if mustHashStringValue(t, first, "class") != "file_slack" {
			continue
		}
		gotOffset := mustHashIntValue(t, first, "offset")
		if gotOffset != want.firstByte+size {
			t.Errorf("%s: ext_slack puts the tail at image offset %d, and e2fsprogs "+
				"puts the file's only block at %d, which with its %d bytes of content "+
				"makes %d -- the two readers disagree about where on the volume this "+
				"file sits", entry.path, gotOffset, want.firstByte, size,
				want.firstByte+size)
		}
		placed++
	}

	if checked == 0 {
		t.Errorf("-corpus.dir is %q and not one ext file's slack was checked", *corpusDir)
	}
	if haveOracle && placed == 0 {
		t.Errorf("the oracle is present and not one file's physical placement was "+
			"compared against it: %d files had their arithmetic checked, so the "+
			"placement comparison is being skipped rather than passing", checked)
	}
	t.Logf("checked the slack arithmetic of %d files and the placement of %d against e2fsprogs",
		checked, placed)
}

// TestExtXattrsAccountForEveryByteTheyReport is a contract check rather than a
// content one, because the corpus carries no xattr oracle.
//
// What it pins: the count matches the list, the total matches the sum, and an
// attribute's storage agrees with whether it has a place on the volume. An
// inline attribute lives in the inode and has no range of its own, so
// located false with no ranges is correct for it and wrong for a block one --
// reporting a block attribute as unlocated would hide where the evidence is.
func TestExtXattrsAccountForEveryByteTheyReport(t *testing.T) {
	handle, ok := openCorpusEXT(t)
	if !ok {
		return
	}

	var listed []extCorpusEntry
	extCorpusWalk(t, handle, "/", 0, &listed)

	checked, withAttrs := 0, 0
	for _, entry := range listed {
		if entry.del {
			continue
		}

		payload, errObj := unwrapPairNoFatal(ExtXattrs(stringObj(handle), stringObj(entry.path)))
		if errObj != nil {
			continue
		}
		result, okHash := payload.(*object.Hash)
		if !okHash {
			t.Fatalf("ext_xattrs payload is not HASH. got=%T", payload)
		}
		checked++

		attrsObj, found := extCorpusField(result, "attributes")
		if !found {
			t.Fatalf("ext_xattrs(%s) published no attributes array", entry.path)
		}
		attrs := attrsObj.(*object.Array)
		if count := mustHashIntValue(t, result, "attribute_count"); count != int64(len(attrs.Elements)) {
			t.Errorf("%s: ext_xattrs says attribute_count %d and its array holds %d",
				entry.path, count, len(attrs.Elements))
		}
		if len(attrs.Elements) > 0 {
			withAttrs++
		}

		var sum int64
		for _, element := range attrs.Elements {
			attr := element.(*object.Hash)
			size := mustHashIntValue(t, attr, "size")
			if size < 0 {
				t.Errorf("%s: ext_xattrs reports a negative size for %q",
					entry.path, mustHashStringValue(t, attr, "name"))
			}
			sum += size

			name := mustHashStringValue(t, attr, "name")
			if name == "" {
				t.Errorf("%s: ext_xattrs reports an attribute with no name", entry.path)
			}
			storage := mustHashStringValue(t, attr, "storage")
			located := mustHashBoolValue(t, attr, "located")
			rangesObj, haveRanges := extCorpusField(attr, "ranges")
			rangeCount := 0
			if haveRanges {
				rangeCount = len(rangesObj.(*object.Array).Elements)
			}
			switch storage {
			case "inline":
				if located || rangeCount > 0 {
					t.Errorf("%s: ext_xattrs says %q is stored inline and still gives "+
						"it %d range(s) with located=%t -- an inline attribute lives in "+
						"the inode and has no extent of its own",
						entry.path, name, rangeCount, located)
				}
			case "block":
				if !located || rangeCount == 0 {
					t.Errorf("%s: ext_xattrs says %q is stored in a block and reports "+
						"located=%t with %d range(s), so the volume offset holding the "+
						"evidence is not published", entry.path, name, located, rangeCount)
				}
			}
			// value_truncated is the bit that makes value_hex quotable.
			if !mustHashBoolValue(t, attr, "value_truncated") {
				hex := mustHashStringValue(t, attr, "value_hex")
				if int64(len(hex)) != size*2 {
					t.Errorf("%s: ext_xattrs says %q is %d bytes and reports %d hex "+
						"characters with value_truncated false",
						entry.path, name, size, len(hex))
				}
			}
		}
		if total := mustHashIntValue(t, result, "total_value_bytes"); total != sum {
			t.Errorf("%s: ext_xattrs says total_value_bytes %d and its attributes sum to %d",
				entry.path, total, sum)
		}
	}

	if checked == 0 {
		t.Errorf("-corpus.dir is %q and not one path's extended attributes were read",
			*corpusDir)
	}
	t.Logf("read the extended attributes of %d paths, %d of which carry some",
		checked, withAttrs)
}
