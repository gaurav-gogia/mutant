package builtin

// Real-image tests for the xfs family, against xfsprogs.
//
// WHY xfsprogs. Every xfs_* builtin reaches the volume through
// github.com/aoiflux/libxfs. xfs_db shares no code with it, so where the two
// agree the agreement means something; where the unit tests' fake backend
// agrees, it agrees with the same reading of the format that the parser used.
//
// WHY xfs_db AND NOT A MOUNT. A loop mount needs root and this machine has
// none. xfs_db reads the image file directly -- and on this volume that
// distinction matters more than usual, because img5_xfs.dd leaves the log's
// tail short of its head and xfs_db therefore REFUSES its whole-filesystem
// walk outright: "The filesystem has valuable metadata changes in a log which
// needs to be replayed." Its per-inode commands still answer, which is how the
// oracle was built. The log turns out to hold only unmount records, so the
// refusal is xfs_db being conservative about tail != head rather than a sign
// that this volume's metadata is mid-transaction.
//
// WHAT THIS FOUND. On img5_xfs.dd, nothing wrong. Measured 2026-10-10 against
// xfsprogs 6.x: all 54 entries agree with xfs_db on path, inode, size and
// type; all 36 regular files hash byte-identical over 953,165,686 bytes; and
// for all 35 files held in a single extent the absolute image offset
// xfs_slack reports for the tail is the extent xfs_db names plus the file's
// length -- so both readers walked the same extent map to the same byte.
//
// TWO THINGS WORTH RECORDING BECAUSE THEY MISLED THE MEASUREMENT FIRST.
//
//   - xfs_log_records reports has_unmount_record true while `xfs_logprint -t`
//     prints state <DIRTY>. Both are right: logprint calls a log dirty
//     whenever tail != head, and this log's records between tail and head are
//     unmount records. The builtin is not contradicting it.
//   - the superblock's fdblocks says 39 free blocks and the AG free-space
//     btrees say 12,929. LAZYSBCOUNT makes the superblock counter the lazy
//     one, and the btrees are authoritative -- 12,929 is also what this
//     volume's own content implies. No xfs_* builtin publishes a free-block
//     figure, so none of them is wrong about it; it is recorded here so the
//     next reader of this image does not take fdblocks for the truth.
//
// WHAT IS NOT COVERED, SAID PLAINLY. xfs_verify runs two checks on this
// volume -- the v5 superblock CRC and the needs-repair incompat bit -- and
// reports verified true with checks_unavailable zero. Neither check looks at
// the log, so a volume captured from a running system reaches the same
// verdict, and nothing in the result says the question was not asked.
// TestXFSVerifyClaimsNoMoreThanItChecked pins what the result does promise
// rather than asserting a check that does not exist.
//
// WHY NOTHING IS PINNED BY VALUE. The corpus images are regenerated and are
// not byte-reproducible, so no digest, count or offset appears in this file.
// Every walk counts what it compared and fails at zero, so a wrong
// -corpus.dir cannot read as a green suite.
//
// THE ORACLE. img5_xfs.dd.xfs-oracle.tsv beside the image, generated by
// xfs_oracle.py, which lives with the corpus rather than in this repository,
// as make_fat_oracle.py does in libfat. It reads each file's extent map with
// xfs_db and then reads the bytes out of the image directly -- neither step
// through libxfs. The tests that need it skip when it is absent.

import (
	"path/filepath"
	"sort"
	"strings"
	"testing"

	"mutant/object"
)

const (
	xfsCorpusImage  = "img5_xfs.dd"
	xfsCorpusOracle = xfsCorpusImage + ".xfs-oracle.tsv"
)

type xfsOracleEntry struct {
	path      string
	inode     int64
	kind      string
	size      int64
	sha256    string
	extents   int64
	firstByte int64
}

type xfsCorpusEntry struct {
	path  string
	name  string
	inode int64
	isDir bool
	size  int64
}

func openCorpusXFS(t *testing.T) (string, bool) {
	t.Helper()

	image, ok := corpusFile(t, xfsCorpusImage)
	if !ok {
		return "", false
	}

	payload, errObj := unwrapPair(t, XFSOpen(stringObj(image)))
	if errObj != nil {
		t.Fatalf("xfs_open(%s): %s", image, errObj.Inspect())
	}
	openHash, okHash := payload.(*object.Hash)
	if !okHash {
		t.Fatalf("xfs_open payload is not HASH. got=%T", payload)
	}

	handle := mustHashStringValue(t, openHash, "handle")
	t.Cleanup(func() { XFSClose(stringObj(handle)) })

	return handle, true
}

func xfsCorpusOracleRows(t *testing.T) (map[string]xfsOracleEntry, bool) {
	t.Helper()

	path, ok := corpusFile(t, xfsCorpusOracle)
	if !ok {
		t.Logf("no %s in this copy of the corpus: the comparison against xfsprogs "+
			"is skipped and only the cross-builtin checks run", xfsCorpusOracle)
		return nil, false
	}

	rows := corpusOracleLines(t, path)
	index := map[string]int{}
	for i, name := range rows[0].fields {
		index[strings.TrimSpace(name)] = i
	}
	for _, required := range []string{
		"path", "inode", "type", "size", "sha256", "nextents", "first_byte_offset",
	} {
		if _, found := index[required]; !found {
			t.Fatalf("%s has no %q column; its header is %v",
				filepath.Base(path), required, rows[0].fields)
		}
	}

	out := map[string]xfsOracleEntry{}
	for _, row := range rows[1:] {
		field := func(name string) string {
			i := index[name]
			if i >= len(row.fields) {
				t.Fatalf("%s line %d has %d fields and %q is column %d",
					filepath.Base(path), row.line, len(row.fields), name, i+1)
			}
			return strings.TrimSpace(row.fields[i])
		}
		entry := xfsOracleEntry{
			path:   field("path"),
			inode:  oracleInt(t, path, row.line, field("inode")),
			kind:   field("type"),
			size:   oracleInt(t, path, row.line, field("size")),
			sha256: field("sha256"),
		}
		if text := field("nextents"); text != "" {
			entry.extents = oracleInt(t, path, row.line, text)
		}
		if text := field("first_byte_offset"); text != "" {
			entry.firstByte = oracleInt(t, path, row.line, text)
		}
		if entry.path == "" {
			t.Fatalf("%s line %d names no path", filepath.Base(path), row.line)
		}
		out[entry.path] = entry
	}
	if len(out) == 0 {
		t.Fatalf("%s holds a header and no rows", filepath.Base(path))
	}
	return out, true
}

// xfsCorpusWalk descends the volume breadth-first, so that a directory loop on
// a damaged volume cannot recurse without bound.
func xfsCorpusWalk(t *testing.T, handle string) []xfsCorpusEntry {
	t.Helper()

	type pending struct {
		dir   string
		depth int
	}
	var out []xfsCorpusEntry
	queue := []pending{{dir: "/", depth: 0}}
	seen := map[string]bool{}
	for len(queue) > 0 {
		dir, depth := queue[0].dir, queue[0].depth
		queue = queue[1:]
		if seen[dir] {
			continue
		}
		seen[dir] = true
		// The seen set already makes a directory cycle terminate; this is the
		// separate question of a tree deep enough that something is wrong with
		// the volume rather than with the walk.
		if depth > 64 {
			t.Fatalf("xfs_list_files descended past 64 levels at %s", dir)
		}

		payload, errObj := unwrapPair(t, XFSListFiles(stringObj(handle), stringObj(dir)))
		if errObj != nil {
			t.Fatalf("xfs_list_files(%s): %s", dir, errObj.Inspect())
		}
		rows, okArr := payload.(*object.Array)
		if !okArr {
			t.Fatalf("xfs_list_files payload is not ARRAY. got=%T", payload)
		}
		for _, element := range rows.Elements {
			row, okRow := element.(*object.Hash)
			if !okRow {
				t.Fatalf("xfs_list_files element is not HASH. got=%T", element)
			}
			entry := xfsCorpusEntry{
				name:  mustHashStringValue(t, row, "name"),
				path:  mustHashStringValue(t, row, "path"),
				inode: mustHashIntValue(t, row, "inode"),
				isDir: mustHashBoolValue(t, row, "is_dir"),
				size:  mustHashIntValue(t, row, "size"),
			}
			if entry.name == "." || entry.name == ".." {
				continue
			}
			out = append(out, entry)
			if entry.isDir {
				queue = append(queue, pending{dir: entry.path, depth: depth + 1})
			}
		}
	}
	return out
}

// TestEveryXFSFileReadsTheBytesXfsdbRead is the comparison this file exists
// for: the content, against a reader that shares no code with ours.
func TestEveryXFSFileReadsTheBytesXfsdbRead(t *testing.T) {
	oracle, haveOracle := xfsCorpusOracleRows(t)
	if !haveOracle {
		t.Skip("no XFS oracle beside the image")
	}
	handle, ok := openCorpusXFS(t)
	if !ok {
		return
	}

	listed := xfsCorpusWalk(t, handle)
	reached := map[string]bool{}
	compared, hashed := 0, 0
	for _, entry := range listed {
		reached[entry.path] = true

		want, found := oracle[entry.path]
		if !found {
			t.Errorf("xfs_list_files reports %s and xfs_db did not: either the oracle "+
				"is stale against this image or the listing invented an entry", entry.path)
			continue
		}
		compared++
		if entry.inode != want.inode {
			t.Errorf("%s: xfs_list_files says inode %d, xfs_db says %d",
				entry.path, entry.inode, want.inode)
		}
		if gotDir, wantDir := entry.isDir, want.kind == "directory"; gotDir != wantDir {
			t.Errorf("%s: xfs_list_files says is_dir=%t, xfs_db says type %q",
				entry.path, gotDir, want.kind)
		}
		if want.kind != "regular" {
			continue
		}
		if entry.size != want.size {
			t.Errorf("%s: xfs_list_files says %d bytes, xfs_db says %d",
				entry.path, entry.size, want.size)
		}

		payload, errObj := unwrapPair(t, XFSHashFile(
			stringObj(handle), stringObj(entry.path), stringObj("sha256")))
		if errObj != nil {
			t.Errorf("xfs_hash_file(%s) refused a file xfs_db read: %s",
				entry.path, errObj.Message)
			continue
		}
		result, okHash := payload.(*object.Hash)
		if !okHash {
			t.Fatalf("xfs_hash_file payload is not HASH. got=%T", payload)
		}
		hashed++

		if got := mustHashStringValue(t, result, "digest"); got != want.sha256 {
			t.Errorf("%s: xfs_hash_file digests %s, xfs_db's extent map and the image "+
				"give %s (mutant size %d, oracle size %d) -- the two readers disagree "+
				"about the bytes", entry.path, got, want.sha256,
				mustHashIntValue(t, result, "size"), want.size)
		}
		if mustHashBoolValue(t, result, "truncated") {
			t.Errorf("%s: xfs_hash_file reports truncated on a file xfs_db read whole",
				entry.path)
		}
		if located := mustHashIntValue(t, result, "located_bytes"); located != want.size {
			t.Errorf("%s: xfs_hash_file located %d bytes of the %d xfs_db read",
				entry.path, located, want.size)
		}
	}

	var dropped []string
	for path := range oracle {
		if !reached[path] {
			dropped = append(dropped, path)
		}
	}
	sort.Strings(dropped)
	if len(dropped) > 0 {
		shown := dropped
		if len(shown) > 12 {
			shown = shown[:12]
		}
		t.Errorf("xfs_db reaches %d entries xfs_list_files never listed, beginning %v",
			len(dropped), shown)
	}

	if compared == 0 {
		t.Errorf("-corpus.dir is %q and not one XFS entry was compared against xfs_db",
			*corpusDir)
	}
	if hashed == 0 {
		t.Errorf("-corpus.dir is %q and not one XFS file was hashed", *corpusDir)
	}
	t.Logf("compared %d entries and %d file digests against xfs_db", compared, hashed)
}

// TestTheXFSFamilyAgreesWithItselfAboutEveryLength needs no oracle.
func TestTheXFSFamilyAgreesWithItselfAboutEveryLength(t *testing.T) {
	handle, ok := openCorpusXFS(t)
	if !ok {
		return
	}

	listed := xfsCorpusWalk(t, handle)
	checked := 0
	for _, entry := range listed {
		if entry.isDir {
			continue
		}

		payload, errObj := unwrapPair(t, XFSMetadata(stringObj(handle), stringObj(entry.path)))
		if errObj != nil {
			t.Errorf("xfs_metadata(%s) refused a path xfs_list_files had just listed: %s",
				entry.path, errObj.Message)
			continue
		}
		metadata, okHash := payload.(*object.Hash)
		if !okHash {
			t.Fatalf("xfs_metadata payload is not HASH. got=%T", payload)
		}
		metaSize := mustHashIntValue(t, metadata, "size")
		if metaSize != entry.size {
			t.Errorf("%s: xfs_list_files says %d bytes and xfs_metadata says %d",
				entry.path, entry.size, metaSize)
		}

		payload, errObj = unwrapPair(t, XFSHashFile(
			stringObj(handle), stringObj(entry.path), stringObj("sha256")))
		if errObj != nil {
			t.Errorf("xfs_hash_file(%s) refused a path xfs_metadata described: %s",
				entry.path, errObj.Message)
			continue
		}
		digest, okHash := payload.(*object.Hash)
		if !okHash {
			t.Fatalf("xfs_hash_file payload is not HASH. got=%T", payload)
		}
		hashSize := mustHashIntValue(t, digest, "size")
		hashedBytes := mustHashIntValue(t, digest, "bytes_hashed")
		truncated := mustHashBoolValue(t, digest, "truncated")

		if hashSize != metaSize {
			t.Errorf("%s: xfs_metadata says %d bytes and xfs_hash_file says %d",
				entry.path, metaSize, hashSize)
		}
		if !truncated && hashedBytes != hashSize {
			t.Errorf("%s: xfs_hash_file hashed %d of %d bytes and reports truncated "+
				"false", entry.path, hashedBytes, hashSize)
		}
		checked++
	}

	if checked == 0 {
		t.Errorf("-corpus.dir is %q and not one XFS file was cross-checked", *corpusDir)
	}
	t.Logf("cross-checked %d files across the listing, the inode and the reader", checked)
}

// TestXFSSlackPlacementMatchesTheExtentMap compares an absolute image offset
// against an independent reader's extent map.
//
// This is the check the cross-builtin ones cannot substitute for: four
// builtins reading the same wrong extent map agree with each other perfectly.
func TestXFSSlackPlacementMatchesTheExtentMap(t *testing.T) {
	oracle, haveOracle := xfsCorpusOracleRows(t)
	if !haveOracle {
		t.Skip("no XFS oracle beside the image")
	}
	handle, ok := openCorpusXFS(t)
	if !ok {
		return
	}

	placed := 0
	for _, entry := range xfsCorpusWalk(t, handle) {
		if entry.isDir {
			continue
		}
		want, found := oracle[entry.path]
		// One extent only: for those the tail's offset is the extent's offset
		// plus the file's length, with nothing to infer.
		if !found || want.kind != "regular" || want.extents != 1 ||
			want.size == 0 || want.firstByte == 0 {
			continue
		}

		payload, errObj := unwrapPairNoFatal(XFSSlack(stringObj(handle), stringObj(entry.path)))
		if errObj != nil {
			continue
		}
		slack, okHash := payload.(*object.Hash)
		if !okHash {
			t.Fatalf("xfs_slack payload is not HASH. got=%T", payload)
		}
		rangesObj, haveRanges := xfsCorpusFieldOf(slack, "ranges")
		if !haveRanges {
			continue
		}
		ranges := rangesObj.(*object.Array)
		if len(ranges.Elements) == 0 {
			continue
		}
		first := ranges.Elements[0].(*object.Hash)
		if mustHashStringValue(t, first, "class") != "file_slack" {
			continue
		}

		gotOffset := mustHashIntValue(t, first, "offset")
		if gotOffset != want.firstByte+want.size {
			t.Errorf("%s: xfs_slack puts the tail at image offset %d, and xfs_db puts "+
				"the file's only extent at %d, which with its %d bytes makes %d -- the "+
				"two readers disagree about where on the volume this file sits",
				entry.path, gotOffset, want.firstByte, want.size,
				want.firstByte+want.size)
		}
		placed++
	}

	if placed == 0 {
		t.Errorf("-corpus.dir is %q and not one XFS file's physical placement was "+
			"compared against xfs_db", *corpusDir)
	}
	t.Logf("compared the placement of %d single-extent files against xfs_db", placed)
}

// TestXFSVerifyClaimsNoMoreThanItChecked pins the two-bit contract rather than
// the checks themselves.
//
// What xfs_verify covers is its own business and is stated in its scope. What
// it must not do is let a reader mistake an unasked question for a passed one:
// the counts have to match the list, an unchecked check must not also claim to
// have passed, and `verified` must not be true while a check failed.
func TestXFSVerifyClaimsNoMoreThanItChecked(t *testing.T) {
	handle, ok := openCorpusXFS(t)
	if !ok {
		return
	}

	payload, errObj := unwrapPair(t, XFSVerify(stringObj(handle)))
	if errObj != nil {
		t.Fatalf("xfs_verify: %s", errObj.Inspect())
	}
	result, okHash := payload.(*object.Hash)
	if !okHash {
		t.Fatalf("xfs_verify payload is not HASH. got=%T", payload)
	}

	checksObj, found := xfsCorpusFieldOf(result, "checks")
	if !found {
		t.Fatalf("xfs_verify published no checks array")
	}
	checks := checksObj.(*object.Array)
	if len(checks.Elements) == 0 {
		t.Fatalf("xfs_verify ran no checks at all and still answered")
	}

	run, passed, failed, unavailable := 0, 0, 0, 0
	for _, element := range checks.Elements {
		check := element.(*object.Hash)
		name := mustHashStringValue(t, check, "name")
		if name == "" {
			t.Errorf("xfs_verify reports a check with no name")
		}
		if detail := mustHashStringValue(t, check, "detail"); strings.TrimSpace(detail) == "" {
			t.Errorf("xfs_verify's %q check carries no detail, so a reader cannot "+
				"tell what passing it means", name)
		}
		wasChecked := mustHashBoolValue(t, check, "checked")
		didPass := mustHashBoolValue(t, check, "passed")
		examined := mustHashIntValue(t, check, "examined")

		if !wasChecked {
			unavailable++
			if didPass {
				t.Errorf("xfs_verify's %q check reports checked false and passed true, "+
					"which publishes an unasked question as an answered one", name)
			}
			if examined != 0 {
				t.Errorf("xfs_verify's %q check reports checked false and examined %d",
					name, examined)
			}
			continue
		}
		run++
		if didPass {
			passed++
			continue
		}
		failed++
	}

	if got := mustHashIntValue(t, result, "checks_run"); got != int64(run) {
		t.Errorf("xfs_verify says checks_run %d and %d of its checks report checked true",
			got, run)
	}
	if got := mustHashIntValue(t, result, "checks_passed"); got != int64(passed) {
		t.Errorf("xfs_verify says checks_passed %d and %d of its checks passed", got, passed)
	}
	if got := mustHashIntValue(t, result, "checks_failed"); got != int64(failed) {
		t.Errorf("xfs_verify says checks_failed %d and %d of its checks failed", got, failed)
	}
	if got := mustHashIntValue(t, result, "checks_unavailable"); got != int64(unavailable) {
		t.Errorf("xfs_verify says checks_unavailable %d and %d of its checks report "+
			"checked false", got, unavailable)
	}
	if mustHashBoolValue(t, result, "verified") && failed > 0 {
		t.Errorf("xfs_verify reports verified true with %d failed check(s)", failed)
	}
	if strings.TrimSpace(mustHashStringValue(t, result, "scope")) == "" {
		t.Errorf("xfs_verify publishes no scope, so what it did not look at is unstated")
	}

	findingsObj, haveFindings := xfsCorpusFieldOf(result, "findings")
	if haveFindings {
		findings := findingsObj.(*object.Array)
		if count := mustHashIntValue(t, result, "finding_count"); count != int64(len(findings.Elements)) {
			t.Errorf("xfs_verify says finding_count %d and its findings array holds %d",
				count, len(findings.Elements))
		}
	}
	t.Logf("xfs_verify: %d checks, %d run, %d passed, %d failed, %d unavailable",
		len(checks.Elements), run, passed, failed, unavailable)
}

// TestXFSLogRecordsReportsAnOrderingItCanDefend checks the one journal of the
// three whose own format settles the ordering question.
//
// An LSN is a cycle and a block, and the cycle counts how many times the log
// has been written round, so ordering by LSN is exact. That is why this
// journal may report `ordering` as lsn where the ext and NTFS ones cannot, and
// why `wrapped` here is a fact about the log rather than a hazard in the
// order. The contract is that the two bits are consistent and that the
// positions bound the entries actually returned.
func TestXFSLogRecordsReportsAnOrderingItCanDefend(t *testing.T) {
	handle, ok := openCorpusXFS(t)
	if !ok {
		return
	}

	payload, errObj := unwrapPair(t, XFSLogRecords(stringObj(handle)))
	if errObj != nil {
		t.Fatalf("xfs_log_records: %s", errObj.Inspect())
	}
	scan, okHash := payload.(*object.Hash)
	if !okHash {
		t.Fatalf("xfs_log_records payload is not HASH. got=%T", payload)
	}

	if !mustHashBoolValue(t, scan, "present") {
		t.Skip("this volume carries no log")
	}
	if ordering := mustHashStringValue(t, scan, "ordering"); ordering != "lsn" {
		t.Errorf("xfs_log_records reports ordering %q: the XFS log's LSN carries the "+
			"cycle count, so this is the one journal that can order itself exactly",
			ordering)
	}
	if !mustHashBoolValue(t, scan, "wrap_checked") {
		t.Errorf("xfs_log_records reports wrap_checked false, so `wrapped` says nothing")
	}

	entriesObj, found := xfsCorpusFieldOf(scan, "entries")
	if !found {
		t.Fatalf("xfs_log_records published no entries array")
	}
	entries := entriesObj.(*object.Array)
	if count := mustHashIntValue(t, scan, "entry_count"); count != int64(len(entries.Elements)) {
		if !mustHashBoolValue(t, scan, "entries_truncated") {
			t.Errorf("xfs_log_records says entry_count %d, its array holds %d, and "+
				"entries_truncated is false", count, len(entries.Elements))
		}
	}

	// The position window has to contain the records returned, or quoting a
	// record against it says the wrong thing about where in the log it sat.
	low := mustHashIntValue(t, scan, "lowest_position")
	high := mustHashIntValue(t, scan, "highest_position")
	if len(entries.Elements) > 0 && low > high {
		t.Errorf("xfs_log_records reports lowest_position %d above highest_position %d",
			low, high)
	}
	for _, element := range entries.Elements {
		record := element.(*object.Hash)
		lsn := mustHashIntValue(t, record, "lsn")
		if lsn < low || lsn > high {
			t.Errorf("xfs_log_records returns a record at LSN %d outside the window "+
				"%d..%d it published", lsn, low, high)
		}
		// Two bits again: a checksum that was not compared cannot be valid.
		if !mustHashBoolValue(t, record, "checksum_checked") &&
			mustHashBoolValue(t, record, "checksum_valid") {
			t.Errorf("xfs_log_records reports a record with checksum_checked false " +
				"and checksum_valid true")
		}
	}
	t.Logf("xfs_log_records: %d records over LSN %d..%d, unmount record %t",
		len(entries.Elements), low, high,
		mustHashBoolValue(t, scan, "has_unmount_record"))
}

// TestXFSUnlinkedAccountsForWhatItScanned is the two-bit contract on the
// unlinked-inode scan.
//
// XFS keeps unlinked-but-open inodes on per-AG hash buckets. An empty answer
// is the ordinary one and is indistinguishable from an unasked question unless
// the counts hold together.
func TestXFSUnlinkedAccountsForWhatItScanned(t *testing.T) {
	handle, ok := openCorpusXFS(t)
	if !ok {
		return
	}

	payload, errObj := unwrapPair(t, XFSUnlinked(stringObj(handle)))
	if errObj != nil {
		t.Fatalf("xfs_unlinked: %s", errObj.Inspect())
	}
	scan, okHash := payload.(*object.Hash)
	if !okHash {
		t.Fatalf("xfs_unlinked payload is not HASH. got=%T", payload)
	}

	entriesObj, found := xfsCorpusFieldOf(scan, "entries")
	if !found {
		t.Fatalf("xfs_unlinked published no entries array")
	}
	entries := entriesObj.(*object.Array)
	count := mustHashIntValue(t, scan, "entry_count")
	if count != int64(len(entries.Elements)) && !mustHashBoolValue(t, scan, "entries_truncated") {
		t.Errorf("xfs_unlinked says entry_count %d, its array holds %d, and "+
			"entries_truncated is false", count, len(entries.Elements))
	}
	if complete := mustHashBoolValue(t, scan, "complete"); !complete {
		if reason := mustHashStringValue(t, scan, "incomplete_reason"); strings.TrimSpace(reason) == "" {
			t.Errorf("xfs_unlinked reports complete false and gives no reason")
		}
	}
	if strings.TrimSpace(mustHashStringValue(t, scan, "scope")) == "" {
		t.Errorf("xfs_unlinked publishes no scope")
	}
	t.Logf("xfs_unlinked: %d entries, complete %t",
		len(entries.Elements), mustHashBoolValue(t, scan, "complete"))
}

// xfsCorpusFieldOf reads one key of a result hash, for keys a test asks about
// rather than requires.
func xfsCorpusFieldOf(h *object.Hash, key string) (object.Object, bool) {
	pair, found := h.Pairs[(&object.String{Value: key}).HashKey()]
	if !found {
		return nil, false
	}
	return pair.Value, true
}
